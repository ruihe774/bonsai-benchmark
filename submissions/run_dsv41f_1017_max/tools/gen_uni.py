import unicodedata, sys

def cat_of(ch):
    c = unicodedata.category(ch)
    if c[0] == 'L': return 1
    if c[0] == 'M': return 2
    if c[0] == 'N': return 3
    return 0

ranges = []
cur = None
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        c = 0
    else:
        c = cat_of(chr(cp))
    if c == 0:
        if cur: ranges.append(cur); cur = None
    else:
        if cur and cur[2] == c and cur[1] == cp - 1:
            cur = (cur[0], cp, c)
        else:
            if cur: ranges.append(cur)
            cur = (cp, cp, c)
if cur: ranges.append(cur)
print("ranges", len(ranges))
ws = []
for cp in list(range(0x09, 0x0E)) + [0x20, 0x85, 0xA0, 0x1680] + list(range(0x2000, 0x200B)) + [0x2028, 0x2029, 0x202F, 0x205F, 0x3000]:
    ws.append(cp)
out = ["// generated by tools/gen_uni.py", "pub const Range = struct { start: u21, end: u21, cat: u8 };", "pub const ranges = [_]Range{"]
for s, e, c in ranges:
    out.append(f"    .{{ .start = {s}, .end = {e}, .cat = {c} }},")
out.append("};")
out.append("pub const ws = [_]u21{ " + ", ".join(str(x) for x in ws) + " };")
out.append("""
pub fn catOf(cp: u21) u8 {
    var lo: usize = 0;
    var hi: usize = ranges.len;
    while (lo < hi) {
        const mid = (lo + hi) / 2;
        const r = ranges[mid];
        if (cp < r.start) hi = mid else if (cp > r.end) lo = mid + 1 else return r.cat;
    }
    return 0;
}

pub fn isSpace(cp: u21) bool {
    for (ws) |w| if (w == cp) return true;
    return false;
}
""")
open("src/uni_tables.zig", "w").write("\n".join(out))
print("wrote src/uni_tables.zig")
